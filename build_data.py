def pin(key, name):
    return marker_url(*P[key], name)


def T(mode, detail):
    return {"mode": mode, "detail": detail}


def S(time, name, key=None, tip="", city="", en="", kind=None, optional=False, transit=None, **kw):
    d = {"time": time, "name": name, "en": en, "amap": pin(key, name) if key else search_url(name, city),
         "rednote": rednote_search_url(name), "tip": tip}
    if kind:
        d["kind"] = kind
    if optional:
        d["optional"] = True
    if transit:
        d["transit"] = transit
    d.update(kw)
    return d


def HOTEL(time, name, key, hotel, note="", event="checkin", transit=None, **kw):
    """A hotel as a stop (hotel-change days)."""
    return S(time, name, key, tip=note, kind="hotel", tripcom=trip_com_search_url(hotel), transit=transit, **kw)


def STAY(key, name, hotel, event, time, note="", transit=None, en=""):
    d = {"name": name, "en": en, "amap": pin(key, name), "tripcom": trip_com_search_url(hotel),
         "event": event, "time": time, "note": note}
    if transit:
        d["transit"] = transit
    return d


def chain(day):
    """Fill transit.amap with a route from the previous entry (same ordering rule as the page)."""
    stay, stops = day.get("stay"), day["stops"]
    ent = list(stops)
    if stay:
        if not stay.get("time"):
            ent = [stay] + ent
        else:
            at = next((i for i, s in enumerate(stops) if s.get("time") and s["time"] > stay["time"]), len(stops))
            ent = ent[:at] + [stay] + ent[at:]
    for prev, cur in zip(ent, ent[1:]):
        tr = cur.get("transit")
        a, b = parse_marker_coords(prev.get("amap", "")), parse_marker_coords(cur.get("amap", ""))
        if tr and a and b and "amap" not in tr:
            tr["amap"] = route_url(a, b, mode=MODE.get(tr["mode"], "bus"))
    if stay and stay.get("transit") and day.get("transit_hub"):
        a, b = parse_marker_coords(day["transit_hub"]["amap"]), parse_marker_coords(stay["amap"])
        if a and b and "amap" not in stay["transit"]:
            stay["transit"]["amap"] = route_url(a, b, mode=MODE.get(stay["transit"]["mode"], "bus"))


